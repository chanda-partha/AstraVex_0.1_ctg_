function shuffleQuestionWithSeed(q: RawQuizQuestion, rng: () => number): QuizQuestion {
  const paired = q.options.map((text, idx) => ({
    text,
    isCorrect: idx === q.correctIndex,
  }));
  for (let i = paired.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [paired[i], paired[j]] = [paired[j], paired[i]];
  }
  return {
    id: q.id,
    topic: q.topic,
    difficulty: q.difficulty,
    question: q.question,
    options: paired.map((p) => p.text),
    correctIndex: paired.findIndex((p) => p.isCorrect),
    explanation: q.explanation,
    healthReward: 10,
    healthPenalty: 5,
  };
}

export function buildClientFallbackQuiz(
  destination: DestinationType,
  missionId: string,
  _hardwareId?: string,
  roundSeed: number = Date.now()
): AIQuizPayload {
  const mKey = (missionId || 'perseverance').toLowerCase();
  const theater = getTheaterForMission(mKey, destination);
  const bank = CLIENT_MISSION_QUIZ_BANKS[mKey];

  let state = (Number(roundSeed) || 1) >>> 0;
  const rng = () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 4294967296;
  };

  if (bank) {
    const pool = [...bank.questions];
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(rng() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    return {
      quizTitle: `${mKey.toUpperCase()} — Mission Certification`,
      destination: theater,
      missionId: mKey,
      specialtyBadge: bank.specialtyBadge,
      roundSeed,
      questions: pool.slice(0, 5).map((q) => shuffleQuestionWithSeed(q, rng)),
    };
  }

  // Fallback bank strictly scoped to theater
  const fallbackPool =
    theater === 'Moon'
      ? CLIENT_MISSION_QUIZ_BANKS.apollo11
      : theater === 'DeepSpace'
        ? CLIENT_MISSION_QUIZ_BANKS.jwst
        : CLIENT_MISSION_QUIZ_BANKS.perseverance;

  return {
    quizTitle: `${theater} Mission Certification`,
    destination: theater,
    missionId: mKey,
    specialtyBadge: fallbackPool.specialtyBadge,
    roundSeed,
    questions: fallbackPool.questions.map((q) => shuffleQuestionWithSeed(q, rng)),
  };
}

